import test from 'node:test'
import assert from 'node:assert/strict'
import {DatabaseSync} from 'node:sqlite'
import {createErdJunction, erdSchemaIssues, erdSql, erdSqlType} from '../src/features/workshop/erd-schema.ts'
import {erdRelationshipError, reattachErdEnd} from '../src/features/workshop/erd-relationship-draft.ts'
